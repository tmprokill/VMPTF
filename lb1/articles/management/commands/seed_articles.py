class Command(BaseCommand):
    help = "Заповнює базу даних тестовими статтями (seed)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--flush",
            action="store_true",
            help="Видалити всі статті перед заповненням",
        )

    def handle(self, *args, **options):
        if options["flush"]:
            deleted, _ = Article.objects.all().delete()
            self.stdout.write(self.style.WARNING(f"Deleted {deleted} articles."))

        now = timezone.now()
        created = 0
        for title, text, author, days_ago in ARTICLES:
            _, was_created = Article.objects.get_or_create(
                title=title,
                defaults={
                    "text": text,
                    "author": author,
                    "published_at": now - timedelta(days=days_ago),
                },
            )
            if was_created:
                created += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Done: created {created} new articles. "
                f"Total in DB: {Article.objects.count()}."
            )
        )
